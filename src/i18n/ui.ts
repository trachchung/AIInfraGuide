const DICT: Record<Lang, Record<UIKey, string>> = { zh, en, vi };

/** Returns a translator for `lang`. `{name}` placeholders are filled from `vars`. */
export function useTranslations(lang: Lang) {
  return (key: UIKey, vars: Record<string, string | number> = {}) =>
    (DICT[lang][key] ?? zh[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

/** Locale from a URL path such as `/AIInfraGuide/zh/cuda/...`. Root paths are the default language. */
export function getLangFromUrl(url: URL): Lang {
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  const rest = url.pathname.startsWith(base) ? url.pathname.slice(base.length) : url.pathname;
  const first = rest.split('/')[1];
  return (LOCALES as readonly string[]).includes(first) ? (first as Lang) : DEFAULT_LANG;
}

/** Path for a site-relative route (`/cuda/...`) in `lang`, with the deploy base prepended. */
export function localePath(lang: Lang, path: string): string {
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  return `${base}${lang === DEFAULT_LANG ? '' : `/${lang}`}${path}`;
}

/** The same page in another language: swaps the locale prefix of the current URL. */
export function switchLangPath(url: URL, to: Lang): string {
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  let rest = url.pathname.startsWith(base) ? url.pathname.slice(base.length) : url.pathname;
  const from = getLangFromUrl(url);
  if (from !== DEFAULT_LANG) rest = rest.slice(from.length + 1) || '/';
  return localePath(to, rest);
}

/** getStaticPaths params for the `[...lang]` route segment: undefined = the default language at the root. */
export const langParams = () => LOCALES.map((l) => (l === DEFAULT_LANG ? undefined : l));
export const langFromParam = (p: string | undefined): Lang => (p as Lang) ?? DEFAULT_LANG;
